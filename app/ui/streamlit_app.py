import streamlit as st

from app.guardrails.input_guardrail import check_input
from app.database.connection import get_engine
from app.metadata.extractor import MetadataExtractor
from app.llm.sql_executor import execute_sql_with_retry



# PAGE CONFIG
st.set_page_config(
    page_title="Sales Insights Assistant",
    page_icon="📊",
    layout="wide",
)



# SESSION STATE
if "history" not in st.session_state:
    st.session_state.history = []



# METADATA
@st.cache_resource
def get_metadata():

    engine = get_engine()

    extractor = MetadataExtractor(engine)

    metadata = extractor.extract_metadata()

    return metadata



# HELPER — FORMAT METADATA FOR LLM
def format_schema(metadata):

    schema_parts = []

    for table, columns in metadata["columns"].items():

        column_text = []

        for column in columns:

            column_text.append(
                f'{column["name"]} ({column["data_type"]})'
            )

        schema_parts.append(
            f"TABLE {table}: "
            + ", ".join(column_text)
        )

    return "\n".join(schema_parts)


def format_relationships(metadata):

    relationships = []

    for fk in metadata["foreign_keys"]:

        relationships.append(
            f'{fk["table"]}.{fk["column"]} -> '
            f'{fk["referenced_table"]}.{fk["referenced_column"]}'
        )

    return "\n".join(relationships)


def format_lov(metadata):

    lov_text = []

    for table, columns in metadata["lov"].items():

        for column, values in columns.items():

            lov_text.append(
                f"{table}.{column}: {values}"
            )

    return "\n".join(lov_text)



# HEADER
st.title("📊 Sales Insights Assistant")

st.write(
    "Ask questions about the Northwind sales database "
    "using natural language."
)

st.info(
    "🔎 Transparency: The SQL generated by the AI is shown "
    "below so you can see what query was executed."
)



# SIDEBAR
with st.sidebar:

    st.header("About")

    st.write(
        """
        This assistant converts natural-language questions
        into read-only SQL queries against the Northwind
        PostgreSQL database.
        """
    )

    st.subheader("Safety")

    st.write("✅ Input guardrails")
    st.write("✅ SQL validation")
    st.write("✅ Output guardrails")
    st.write("✅ Result sanitization")
    st.write("✅ Query tracing")
    st.write("✅ Retry handling")

    if st.button("Clear conversation"):

        st.session_state.history = []

        st.rerun()



# QUESTION INPUT
question = st.chat_input(
    "Ask a question about sales..."
)



# PROCESS QUESTION
if question:

    
    # 1. INPUT GUARDRAIL
    guardrail_result = check_input(question)

    if not guardrail_result["allowed"]:

        st.error(
            f"🚫 Request blocked: "
            f"{guardrail_result['reason']}"
        )

        st.caption(
            "The request was blocked before reaching the LLM."
        )

        st.session_state.history.append(
            {
                "question": question,
                "blocked": True,
                "reason": guardrail_result["reason"],
            }
        )

    else:

        
        # 2. SANITIZED INPUT
        safe_question = guardrail_result[
            "sanitized_input"
        ]

        if guardrail_result["pii_detected"]:

            st.warning(
                "⚠️ An email address was detected and "
                "redacted before processing."
            )

        
        # 3. GET METADATA
        try:

            with st.spinner(
                "Reading database metadata..."
            ):

                metadata = get_metadata()

            schema = format_schema(metadata)

            relationships = format_relationships(
                metadata
            )

            lov = format_lov(metadata)

        except Exception as exc:

            st.error(
                "Unable to retrieve database metadata. "
                "Please try again later."
            )

            st.stop()

        # -------------------------------------------------
        # 4. EXECUTE COMPLETE BACKEND PIPELINE
        # -------------------------------------------------

        try:

            with st.spinner(
                "Generating and validating SQL..."
            ):

                result = execute_sql_with_retry(
                    question=safe_question,
                    schema=schema,
                    relationships=relationships,
                    lov=lov,
                )

        except Exception:

            st.error(
                "Something went wrong while processing "
                "your request. Please try again."
            )

            st.stop()

        
        # 5. DISPLAY TRACE ID
        trace_id = result.get(
            "trace_id",
            "Unavailable"
        )

        st.caption(
            f"🔎 Trace ID: `{trace_id}`"
        )

        
        # 6. HANDLE FAILURE
        if not result["success"]:

            error_type = result.get(
                "error_type",
                "unknown"
            )

            error_message = result.get(
                "error",
                "Unknown error"
            )

            if error_type in [
                "validation",
                "output_guardrail",
            ]:

                st.error(
                    "🚫 The generated query was blocked "
                    "by the safety checks."
                )

            elif error_type == "database":

                st.error(
                    "⚠️ The query could not be executed. "
                    "The system attempted to correct it "
                    "automatically."
                )

            else:

                st.error(
                    "⚠️ We couldn't process that request."
                )

            with st.expander("Technical details"):

                st.write(error_message)

            st.session_state.history.append(
                {
                    "question": question,
                    "trace_id": trace_id,
                    "success": False,
                    "error": error_message,
                }
            )

        else:

            
            # 7. GENERATED SQL
            st.subheader("🧠 Generated SQL")

            st.code(
                result["sql"],
                language="sql"
            )

            
            # 8. CONFIDENCE / CAVEAT
            st.info(
                "ℹ️ The answer is based only on the available "
                "Northwind database data. Generated SQL is "
                "validated and restricted to read-only queries."
            )

            
            # 9. RESULTS
            st.subheader("📊 Results")

            columns = result["columns"]
            rows = result["rows"]

            if rows:

                # Convert rows into dictionaries
                data = []

                for row in rows:

                    data.append(
                        dict(
                            zip(columns, row)
                        )
                    )

                st.dataframe(
                    data,
                    use_container_width=True,
                    hide_index=True,
                )

                st.success(
                    result.get(
                        "message",
                        f"{len(rows)} result(s) found."
                    )
                )

            else:

                st.warning(
                    "No matching results were found. "
                    "This may mean that the database contains "
                    "no matching records."
                )

            
            # 10. ATTEMPTS
            st.caption(
                f"SQL generation attempts: "
                f"{result.get('attempts', 1)}"
            )

            
            # 11. SAVE HISTORY
            st.session_state.history.append(
                {
                    "question": question,
                    "trace_id": trace_id,
                    "success": True,
                    "sql": result["sql"],
                    "columns": columns,
                    "rows": rows,
                }
            )


# CONVERSATION HISTORY
if st.session_state.history:

    st.divider()

    st.subheader("📝 Conversation History")

    for index, item in enumerate(
        reversed(st.session_state.history)
    ):

        with st.expander(
            f"Question {len(st.session_state.history) - index}: "
            f"{item['question']}"
        ):

            if item.get("blocked"):

                st.error(
                    f"Blocked: {item['reason']}"
                )

                continue

            if not item.get("success"):

                st.error(
                    item.get(
                        "error",
                        "Request failed."
                    )
                )

                if item.get("trace_id"):

                    st.caption(
                        f"Trace ID: `{item['trace_id']}`"
                    )

                continue

            st.caption(
                f"Trace ID: `{item['trace_id']}`"
            )

            st.code(
                item["sql"],
                language="sql"
            )

            if item["rows"]:

                data = []

                for row in item["rows"]:

                    data.append(
                        dict(
                            zip(
                                item["columns"],
                                row
                            )
                        )
                    )

                st.dataframe(
                    data,
                    use_container_width=True,
                    hide_index=True,
                )

            else:

                st.write("No results found.")